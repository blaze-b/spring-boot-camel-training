CREATE TABLE enrolment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      VARCHAR(32)  NOT NULL,
    course_code     VARCHAR(32)  NOT NULL,
    enrolled_date   DATE         NOT NULL,
    status          VARCHAR(32)  NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_enrolment_idempotency ON enrolment (idempotency_key);
CREATE INDEX idx_enrolment_status ON enrolment (status);

CREATE TABLE enrolment_audit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id  BIGINT       NOT NULL,
    student_id    VARCHAR(32)  NOT NULL,
    course_code   VARCHAR(32)  NOT NULL,
    enrolled_date DATE         NOT NULL,
    lane          VARCHAR(32)  NOT NULL,
    report_line   VARCHAR(256) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_enrolment_audit_enrolment_id ON enrolment_audit (enrolment_id);
